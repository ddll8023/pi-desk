/**
 * Thinking 折叠态预览：把思考正文压成一行纯文本，供折叠卡片在标题行下方展示。
 *
 * 取正文尾部而不是头部：折叠态要回答的是「现在在想什么」，流式期间头部内容早已读不到。
 * 先截尾再清理标记，每次流式更新只处理固定长度的片段，不在渲染线程扫全文。
 * 清理只去掉会干扰单行观感的 Markdown 标记，不追求与正文渲染等价；行内的单个 `*`/`_` 与成对 `__` 一律保留，
 * 避免把 `snake_case`、`__init__` 这类标识符改坏。块被投影截断时保留的是头部，此时预览取到的是保留
 * 片段的尾部，不再是模型最新输出（卡片上的截断提示与之一致）。
 */

/** 折叠态两行预览的字符上限：宽屏约两行，窄屏由 CSS 裁切并渐隐。 */
export const THINKING_PREVIEW_CHARS = 300

/** 取思考正文尾部的单行预览；没有可展示内容时返回空串。 */
export function thinkingPreviewText(text: string): string {
  return text
    .slice(-THINKING_PREVIEW_CHARS)
    .replace(/```[\w-]*\n?/g, ' ')
    .replace(/`([^`\n]*)`/g, '$1')
    .replace(/!\[[^\]]*\]\([^)]*\)/g, ' ')
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/(\*\*|~~)(.+?)\1/g, '$2')
    .replace(/^[ \t]{0,3}(#{1,6}|>|[-*+]|\d+[.)])[ \t]+/gm, '')
    .replace(/\s+/g, ' ')
    .trim()
}
